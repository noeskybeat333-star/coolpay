<?php

namespace App\Filament\Widgets;

/**
 * Доступные ширины виджета в колонках сетки из шести.
 *
 * Отдельный класс, а не константа трейта: константы трейта в PHP
 * читаются только через использующий класс, а список нужен и
 * странице настроек, у которой этого трейта нет.
 *
 * Ноль означает «скрыт»: один список управляет и размером, и
 * составом дашборда.
 */
final class WidgetWidth
{
    public const OPTIONS = [
        0 => 'Скрыт',
        1 => 'Одна шестая',
        2 => 'Треть',
        3 => 'Половина',
        4 => 'Две трети',
        5 => 'Пять шестых',
        6 => 'Вся ширина',
    ];

    public const DEFAULT = 6;

    public const MIN = 1;

    public const MAX = 6;
}
